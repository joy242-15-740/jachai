"""`python -m jachai.eval` (what `make eval` runs).

Reads the world from data/world, builds features, then writes:
  reports/leakage_check.md  single-feature AUC per feature, payment and shop level
  reports/baselines.md      rules-only and blanket-limit baseline metrics
Exits with an error if any single feature is above the leakage threshold.
"""

from __future__ import annotations

import sys

import pandas as pd

from jachai.eval.baselines import evaluation_window, run_baselines
from jachai.eval.leakage import check, single_feature_auc
from jachai.features import build_features
from jachai.features.config import load_thresholds
from jachai.labels.config import load_rules
from jachai.world.config import load_world_config
from jachai.world.generate import read_world_tables
from jachai.world.summary import default_report_path, default_world_dir, md_table
from jachai.world.world import TRUE_LABEL

HEADER = "Generated by `make eval` (`python -m jachai.eval`). Synthetic data only."


def leakage_tables(tables, feats, cfg, thr) -> dict[str, pd.DataFrame]:
    pay = feats["payments"][evaluation_window(feats["payments"], cfg, thr.eval.warmup_days)]
    pay_truth = pay["payment_id"].map(tables["qr_payments"].set_index("payment_id")[TRUE_LABEL])
    sd = feats["shop_day"]
    last = sd[sd["day"] == sd["day"].max()]
    shop_truth = last["shop_id"].map(tables["shops"].set_index("shop_id")[TRUE_LABEL])
    return {
        "payment": single_feature_auc(pay, pay_truth.to_numpy()),
        "shop (last day)": single_feature_auc(last, shop_truth.to_numpy()),
    }


def render_leakage(results: dict[str, pd.DataFrame], max_auc: float) -> tuple[str, bool]:
    parts = [
        "# Single-feature leakage check",
        HEADER,
        f"Each feature alone, scored against the hidden true label. Strength = "
        f"max(AUC, 1 - AUC). Threshold: {max_auc} (configs/thresholds.yaml). A feature "
        "above it means a leak or a too-easy synthetic world.",
    ]
    ok = True
    for level, table in results.items():
        bad = check(table, max_auc)
        ok &= bad.empty
        status = "PASS" if bad.empty else f"FAIL ({len(bad)} above threshold)"
        parts += [f"## {level}: {status}", md_table(table.set_index("feature").round(3))]
    return "\n\n".join(parts) + "\n", ok


def main() -> None:
    cfg, thr, rules = load_world_config(), load_thresholds(), load_rules()
    tables = read_world_tables(default_world_dir())
    feats = build_features(tables, cfg, thr.features)
    reports = default_report_path().parent

    baselines = run_baselines(tables, feats, cfg, thr, rules)
    text = "\n\n".join(
        [
            "# Baselines",
            HEADER,
            f"Scored after a {thr.eval.warmup_days}-day warm-up, against the hidden truth. "
            "`rules_only`: labeling functions as a detector. `blanket_limit`: every shop "
            f"capped at Tk {rules.baselines.blanket_limit.daily_cap:,.0f} per day.",
            md_table(baselines.T.round(3)),
        ]
    )
    (reports / "baselines.md").write_text(text + "\n", encoding="utf-8")

    leak_text, ok = render_leakage(
        leakage_tables(tables, feats, cfg, thr), thr.leakage.max_single_feature_auc
    )
    (reports / "leakage_check.md").write_text(leak_text, encoding="utf-8")
    print(text, "\n\n", leak_text)
    print(f"Written to {reports}/baselines.md and {reports}/leakage_check.md")
    if not ok:
        sys.exit("Leakage check FAILED: see reports/leakage_check.md")


if __name__ == "__main__":
    main()
